"""Builds kana trigram counts for jaen::FixTypo from Mozc's own dictionary readings.

  python tools/build_kana_model.py --mozc <mozc/src> --out <kana_model_data.inc>

Each distinct reading in data/dictionary_oss/dictionary0*.txt counts once
(frequent words are not weighted). "^" and "$" mark reading edges. Trigrams
seen fewer than --min-count times are dropped.
"""
import argparse
import re
from collections import Counter
from pathlib import Path

KANA = re.compile(r"[ぁ-ゖー]+")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--mozc", type=Path, required=True)
    parser.add_argument("--out", type=Path, required=True)
    parser.add_argument("--min-count", type=int, default=2)
    args = parser.parse_args()
    readings = set()
    for path in sorted((args.mozc / "data/dictionary_oss").glob("dictionary0*.txt")):
        for line in path.read_text(encoding="utf-8").splitlines():
            reading = line.split("\t", 1)[0]
            if KANA.fullmatch(reading):
                readings.add(reading)
    counts = Counter()
    for reading in readings:
        text = "^^" + reading + "$"
        for i in range(len(text) - 2):
            counts[text[i:i + 3]] += 1
    kept = sorted((t, c) for t, c in counts.items() if c >= args.min_count)
    with args.out.open("w", encoding="utf-8", newline="\n") as out:
        out.write("// Generated by tools/build_kana_model.py from Mozc dictionary_oss readings.\n")
        out.write("inline constexpr KanaTrigram kKanaTrigrams[] = {\n")
        for trigram, count in kept:
            out.write(f'    {{"{trigram}", {count}}},\n')
        out.write("};\n")
    print("readings", len(readings), "trigrams", len(kept))


if __name__ == "__main__":
    main()
