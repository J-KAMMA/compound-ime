def write_tests(rows, path, comment):
    out = ["# " + comment,
           "# 列: ローマ字<TAB>元の文<TAB>区分<TAB>番号。tools/make_toku_tests.py で作成。"]
    for n, (raw, expected, category) in enumerate(rows, 1):
        out.append(f"{raw}\t{expected}\t{category}\tt{n:04d}")
    path.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--table", type=Path, required=True)
    ap.add_argument("--tests-dir", type=Path, default=HERE.parent / "tests/conversion")
    ap.add_argument("--words", type=Path, default=HERE / "data/toku.tsv")
    args = ap.parse_args()
    table = rv.load_table(args.table)
    rev = rv.reverse_table(table)

    def romaji(kana):
        raw = rv.write(kana, "base", rev)
        if not raw or rv.to_kana(raw, table) != kana:
            raise SystemExit(f"ローマ字にできない: {kana}")
        return raw

    toku_rows, words = [], {}
    n = 0
    for surface_stem, reading_stem, kind, objects in VERBS:
        for suffix in SUFFIXES[kind]:
            reading = reading_stem + suffix
            surface = surface_stem + suffix
            category = "どく" if suffix.startswith(("んど", "いど")) else "とく"
            if kind == "ion_ku":
                word_kind = "verb_toku_ku"
            elif kind == "ion_gu":
                word_kind = "verb_doku_gu"
            elif kind == "hatsuon":
                word_kind = "verb_doku_hatsuon"
            elif kind == "renyou":
                word_kind = "verb_toku_suru" if reading_stem.endswith("し") else "verb_toku_ichidan"
            elif reading_stem in ("か", "い"):
                word_kind = "verb_toku_wa"
            else:
                word_kind = "verb_toku_godan"
            words[(reading, surface)] = word_kind
            for obj in objects[:2 if n < TWO_OBJECTS else 1]:
                ending = "いい。" if suffix.endswith("けば") else "。"
                sentence = obj + surface + ending
                kana = OBJECT_READINGS[obj] + reading + ending
                toku_rows.append((romaji(kana), sentence, category))
        n += 1
    for reading, expected in KITTO_BARE:
        toku_rows.append((romaji(reading), expected, "報告"))
    for reading, expected, category in ADVERBS:
        toku_rows.append((romaji(reading), expected, "同音・" + category))
    write_tests(toku_rows, args.tests_dir / "toku.tsv",
                "〜ておくの縮約（〜とく・〜どく）と、きっと・もっと・ずっと・ちょっと・得・解く・説く・毒・退くの紛らわしい文。")
    with args.words.open("w", encoding="utf-8", newline="\n") as out:
        out.write("# 〜ておくの縮約の辞書（読み<TAB>表記<TAB>種類）。tools/make_toku_tests.py で作成。\n")
        for (reading, surface), word_kind in sorted(words.items()):
            out.write(f"{reading}\t{surface}\t{word_kind}\n")

    naru_rows = []
    for reading, expected in NARU:
        for rform, eform in NARU_FORMS:
            naru_rows.append((romaji(reading + rform + "。"), expected + eform + "。", "になる"))
    for reading, expected in UKERU:
        naru_rows.append((romaji(reading), expected, "担う"))
    for reading, expected in NARU_KEEP:
        naru_rows.append((romaji(reading), expected, "になる"))
    for reading, expected in NARU_BARE:
        naru_rows.append((romaji(reading), expected, "報告"))
    for reading, expected in NATTOKU:
        naru_rows.append((romaji(reading), expected, "納得"))
    write_tests(naru_rows, args.tests_dir / "naru.tsv",
                "〜になってる・〜になってた・〜になっちゃう・〜になっとくの縮約と、担うが正しい文。")


if __name__ == "__main__":
    main()
