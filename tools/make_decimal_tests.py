def write(name, header, data):
    seen = set()
    lines = []
    for r, w, c in data:
        if r in seen:
            continue
        seen.add(r)
        lines.append(f"{r}\t{w}\t{c}")
    (out_dir / name).write_text(header + "\n".join(lines) + "\n", encoding="utf-8")
    print(name, len(lines))


