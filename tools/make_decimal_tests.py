"""数字の間の点（小数点・桁区切り）と文末の句点の試験の文を作る。

  python tools/make_decimal_tests.py [出力先 tests/conversion]

出力（毎回同じ。乱数は使わない）:
  decimal.tsv     数字を含む文: ローマ字（数字・「.」「,」「%」はそのまま打つ）<TAB>期待<TAB>区分
                  区分: 小数、版の番号、アドレスの番号、金額、割合、かなの数の語、英語まじり、
                        文末の数字（「合計は4.」→「合計は4。」）、数字のあとの読点（「りんご3,みかん2」）
  decimal-ja.tsv  数字を含まない普通の日本語の文（文末の「。」と読点「、」だけが決め手）

期待は数字の設定が半角のときの形（4.1、1,000円）。漢字・かなの選び方は採点しない
（tools/score_decimal.py は数字と「. , 。、%」の並びだけを見る）。
決め方（docs/decimal-point.md）:
  数字の間の「.」「,」は半角の点・コンマ。数字のあとで文や節が終わる「.」「,」は「。」「、」。
"""
