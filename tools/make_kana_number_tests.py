# ---- 文末の句点のあとでも取る（にひゃっぷん。）、時の言葉のあとの に は数の一部。
BOUNDARY = [
    ("にひゃっぷん", "200分"), ("にじゅうにん", "20人"), ("さんぜんえん", "3000円"),
    ("にせんにじゅうろくねん", "2026年"), ("じゅうじ", "10時"), ("にじゅうてん", "20点"),
]
TIME_ROWS = [
    ("きょう", "今日", "にじゅうにん", "20人"),
    ("きのう", "昨日", "にじゅうにん", "20人"),
    ("あした", "明日", "にじゅうにん", "20人"),
]


def build():
    rows = []
    for kana, want in NUMBERS:
        for i, (before, after) in enumerate(FRAMES[:2]):
            rows.append((*sentence(before, (kana, want), after), "数と単位"))
        rows.append((*sentence((kana, want), ("。", "。")), "文末"))
    for kana, want in BOUNDARY:
        # 打つ記号は、キーボードにある半角の ! ? と [ ]（Mozc が ！ ？ 「 」 にする）。
        for after in (("。", "。"), ("!", "！"), ("?", "？")):
            rows.append((*sentence((kana, want), after), "文末"))
        rows.append((*sentence(("[", "「"), (kana, want), ("]", "」")), "文末"))
    # 数のあとに語が続く形（40分待ちました、20年後にまた会いましょう）。
    rows.append((*sentence(("よんじゅっぷん", "40分"), ("まちました。", "待ちました。")), "数のあとの語"))
    rows.append((*sentence(("にじゅうねん", "20年"), ("ごにまたあいましょう。", "後にまた会いましょう。")), "数のあとの語"))
    for before_kana, before_want, kana, want in TIME_ROWS:
        rows.append((*sentence((before_kana, before_want), (kana, want), ("。", "。")), "時の言葉"))
    ja = []
    for kana, want in WORDS:
        for before, after in JA_FRAMES:
            ja.append((*sentence(before, (kana, want), after), "和語・普通の言葉"))
    return rows, ja


