def romaji(kana):
    out, i = [], 0
    while i < len(kana):
        c = kana[i]
        if c == "っ":
            nxt = romaji(kana[i + 1:i + 3])
            out.append(nxt[0])
            i += 1
            continue
        if i + 1 < len(kana) and kana[i + 1] in DIGRAPH and c in DIGRAPH_BASE:
            out.append(DIGRAPH_BASE[c] + DIGRAPH[kana[i + 1]][1:])
            i += 2
            continue
        out.append(BASE.get(c, c))
        i += 1
    return "".join(out)


def sentence(*parts):
    kana = "".join(p[0] for p in parts)
    want = "".join(p[1] for p in parts)
    return romaji(kana), want


